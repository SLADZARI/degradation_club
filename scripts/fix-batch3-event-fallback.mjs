import fs from 'node:fs';
const path='visual-standard-v2.css';
let css=fs.readFileSync(path,'utf8');
const marker='/* Any remaining event media uses the same upper-right crop rule. */';
const next='/* Existing Fuengirola Dementor section is normalized as a Relation without changing copy. */';
const start=css.indexOf(marker);
const end=css.indexOf(next,start);
if(start>=0 && end>start) css=css.slice(0,start)+css.slice(end);
fs.writeFileSync(path,css);
console.log('Batch 3 event fallback cleanup applied');
