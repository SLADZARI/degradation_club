import path from 'node:path';

export const TARGETS = new Set(['VM_STATIC', 'PAGES_FALLBACK']);

export function requireArtifactTarget(argv = process.argv.slice(2)) {
  if (argv.length !== 1 || !/^--target=(VM_STATIC|PAGES_FALLBACK)$/.test(argv[0])) {
    throw new Error('Explicit --target=VM_STATIC or --target=PAGES_FALLBACK required; implicit artifact selection forbidden');
  }
  return argv[0].slice('--target='.length);
}

// Applies to release ARTIFACT paths, never to the original source tree or
// the currently served VM directory. Public JSON/TXT runtime is not blanket-blocked.
const forbiddenSegments = new Set([
  '.git', '.github', '.weekly-os', 'node_modules', 'docs', 'references',
  'scripts', 'test', 'tests', 'fixtures', 'staging', 'migrations',
  'backups', 'backup', '__pycache__', '.venv', 'operations',
]);
const forbiddenNames = new Set([
  '.gitignore', '.gitattributes', '.ds_store', '.env', 'dockerfile',
  'makefile', 'vercel.json', 'package.json', 'package-lock.json',
  'pnpm-lock.yaml', 'yarn.lock', 'production-route-manifest.json',
  'deploy_trigger.txt', '.deploy-trigger',
]);
const forbiddenExtensions = new Set([
  '.sql', '.b64', '.base64', '.toml', '.ts', '.tsx', '.yaml', '.yml',
  '.bak', '.backup', '.dump', '.db', '.sqlite', '.sqlite3',
  '.pem', '.key', '.sh', '.py', '.map', '.zip', '.tar', '.tgz',
]);

export function artifactForbiddenReason(relative, target, fromSource = false) {
  if (!TARGETS.has(target)) throw new Error('Invalid target');
  const rel = String(relative).replaceAll('\\', '/');
  const parts = rel.split('/');
  if (!rel || rel.startsWith('/') || parts.some(p => !p || p === '.' || p === '..'))
    return 'unsafe artifact path';
  const normalized = parts.map(x => x.toLowerCase());
  const base = normalized.at(-1);
  const rootOnly = normalized.length === 1;

  if (rootOnly && (base === 'cname' || base === '.nojekyll')) {
    if (fromSource) return 'generated metadata must never be source-copied';
    return target === 'VM_STATIC' ? 'Pages-only metadata forbidden on VM' : null;
  }
  if (normalized.some((segment, index) =>
    forbiddenSegments.has(segment) &&
    !(index === 2 && normalized[0] === 'workspace' &&
      normalized[1] === 'admin' && segment === 'tests')))
    return 'source-only directory';
  if (normalized.some(segment => segment.startsWith('.env')))
    return 'environment metadata';
  if (base.startsWith('.') && base !== '.well-known')
    return 'hidden source material';
  if (forbiddenNames.has(base)) return 'source-only configuration';
  if (forbiddenExtensions.has(path.posix.extname(base)))
    return 'source-only file extension';
  // CNAME and .nojekyll are allowed only at the Pages root, generated by builder.
  if (base === 'cname' || base === '.nojekyll') return 'nested deployment metadata';
  return null;
}
